/**
 * KALINAR DAEMON WATCHER (v0.1.0-alpha)
 * Chokidar Multi-Workspace Watcher with 300ms Debounce and .kalinar-lock Loop Suppression
 * Strictly Zero Emojis
 */

import chokidar, { FSWatcher } from 'chokidar';
import path from 'node:path';
import fs from 'node:fs';
import { ZenFirewall } from '../../src/core/ZenFirewall.js';
import { KalinarSqliteStore } from '../db/sqliteStore.js';
import { KalinarEventBus } from '../../src/core/KalinarEventBus.js';

export interface DaemonConfig {
  workspacePath: string;
  debounceMs: number;
  lockFile: string;
}

export class KalinarDaemon {
  private watcher: FSWatcher | null = null;
  private config: DaemonConfig;
  private zenFirewall: ZenFirewall;
  private store: KalinarSqliteStore;
  private eventBus: KalinarEventBus;
  private debounceTimers: Map<string, NodeJS.Timeout> = new Map();
  private auditCycles = 0;
  private isRunning = false;

  constructor(
    config?: Partial<DaemonConfig>,
    store?: KalinarSqliteStore,
    eventBus?: KalinarEventBus
  ) {
    this.config = {
      workspacePath: config?.workspacePath || process.cwd(),
      debounceMs: config?.debounceMs || 300,
      lockFile: config?.lockFile || '.kalinar-lock',
    };
    this.zenFirewall = ZenFirewall.getInstance();
    this.store = store || new KalinarSqliteStore();
    this.eventBus = eventBus || KalinarEventBus.getInstance();
  }

  public async start(): Promise<void> {
    if (this.isRunning) return;

    await this.zenFirewall.initialize();

    const ignoredPatterns = [
      /(^|[/\\])\.git([/\\]|$)/,
      /(^|[/\\])node_modules([/\\]|$)/,
      /(^|[/\\])dist([/\\]|$)/,
      /(^|[/\\])dist-electron([/\\]|$)/,
      /(^|[/\\])\.next([/\\]|$)/,
      /\.db-wal$/,
      /\.db-shm$/,
      /TASK_LOCK\.json$/,
    ];

    this.watcher = chokidar.watch(this.config.workspacePath, {
      ignored: ignoredPatterns,
      persistent: true,
      ignoreInitial: true,
      awaitWriteFinish: {
        stabilityThreshold: 100,
        pollInterval: 50,
      },
    });

    this.watcher
      .on('add', (filePath) => this.handleFileEvent('add', filePath))
      .on('change', (filePath) => this.handleFileEvent('change', filePath))
      .on('unlink', (filePath) => this.handleFileEvent('unlink', filePath))
      .on('error', (err) => console.error('[WATCHER_ERROR]:', err));

    this.isRunning = true;
  }

  private handleFileEvent(event: 'add' | 'change' | 'unlink', filePath: string): void {
    // Sliding window debounce (300ms)
    const existing = this.debounceTimers.get(filePath);
    if (existing) {
      clearTimeout(existing);
    }

    const timer = setTimeout(async () => {
      this.debounceTimers.delete(filePath);
      await this.processDebouncedEvent(event, filePath);
    }, this.config.debounceMs);

    this.debounceTimers.set(filePath, timer);
  }

  private async processDebouncedEvent(event: 'add' | 'change' | 'unlink', filePath: string): Promise<void> {
    // Check if internal agent lock is active (single-writer suppression)
    const lockPath = path.resolve(this.config.workspacePath, this.config.lockFile);
    if (fs.existsSync(lockPath)) {
      // Internal write generated by active turn - drop loop to prevent storms
      return;
    }

    const normalizedPath = filePath.replace(/\\/g, '/');

    // Evaluate via GoRules ZEN Firewall (< 1ms)
    const { result: routingDecision, latencyMs } = await this.zenFirewall.evaluateEventRouter({
      eventType: 'FILE_CHANGE',
      filePath: normalizedPath,
      auditCycle: this.auditCycles,
    });

    if (routingDecision.action === 'DROP_LOOP_SUPPRESSED' || routingDecision.action === 'IGNORE_HARD') {
      return;
    }

    if (routingDecision.action === 'HALT_AUDIT_CYCLE_CAP') {
      this.eventBus.emit('circuit_breaker:state_changed', {
        state: 'OPEN',
        reason: 'AUDIT_CYCLE_CAP_EXCEEDED (MAX 2)',
      });
      return;
    }

    const category =
      routingDecision.action === 'WATCH_VISUAL_ONLY' ? 'WATCH_VISUAL_ONLY' : 'STANDARD_WATCH';

    // Telemetry log to SQLite
    this.store.insertTelemetry({
      task_id: 'WORKSPACE_DAEMON',
      event_type: 'FILE_WATCH',
      agent_name: 'kalinar-daemon',
      payload: JSON.stringify({
        event,
        filePath: normalizedPath,
        action: routingDecision.action,
        tag: routingDecision.secondBrainTag,
      }),
      latency_ms: Math.round(latencyMs),
    });

    // Emit event bus notification
    this.eventBus.emit('watcher:file_event', {
      path: normalizedPath,
      event,
      category,
    });

    // If visual canvas modified, trigger canvas sync
    if (normalizedPath.endsWith('KALINAR_GALAXY.canvas')) {
      this.store.syncFromCanvas(normalizedPath);
      this.eventBus.emit('canvas:sync_requested', {
        canvasFile: normalizedPath,
        nodesCount: 1,
      });
    }
  }

  public getStatus(): { isRunning: boolean; auditCycles: number; debounceMs: number } {
    return {
      isRunning: this.isRunning,
      auditCycles: this.auditCycles,
      debounceMs: this.config.debounceMs,
    };
  }

  public async stop(): Promise<void> {
    for (const timer of this.debounceTimers.values()) {
      clearTimeout(timer);
    }
    this.debounceTimers.clear();

    if (this.watcher) {
      await this.watcher.close();
      this.watcher = null;
    }
    this.isRunning = false;
  }
}
